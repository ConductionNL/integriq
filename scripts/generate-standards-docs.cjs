// generate-standards-docs.cjs — writes the "Standards & federation" docs page
// and the matching README section from the `discovery` block in
// src/manifest.json.
//
// WHY GENERATED. The same block is what OpenRegister publishes to other
// servers (anonymous /ocs/v2.php/cloud/capabilities, key `<appId>.discovery`,
// and OCM resource types in /.well-known/ocm). A hand-written page would drift
// from what the server actually tells the world; a generated one cannot.
// Edit the manifest, run `npm run docs:standards`, commit both.
//
// Tier A canonical file (docs/canonical-files.md): identical in every app.
//
// Usage:
//   node scripts/generate-standards-docs.cjs           write the page + README section
//   node scripts/generate-standards-docs.cjs --check   exit 1 when either is out of date
//
// The README section lives between `<!-- discovery:start -->` and
// `<!-- discovery:end -->`. When the markers are missing the section is
// inserted before "## Standards & Compliance", else before "## Related Apps",
// "## License" or at the end.
//
// Field reference and the shared vocabulary of standard ids:
// https://github.com/ConductionNL/openregister/blob/development/docs/Technical/discovery-and-federation.md

'use strict'

const fs = require('fs')
const path = require('path')

const ROOT = path.resolve(__dirname, '..')
const MANIFEST = path.join(ROOT, 'src', 'manifest.json')
const INFO_XML = path.join(ROOT, 'appinfo', 'info.xml')
const PAGE = path.join(ROOT, 'docs', 'standards-and-federation.md')
const README = path.join(ROOT, 'README.md')
const START = '<!-- discovery:start -->'
const END = '<!-- discovery:end -->'
const REFERENCE = 'https://github.com/ConductionNL/openregister/blob/development/docs/Technical/discovery-and-federation.md'

const ACCESS = {
	public: 'Public',
	token: 'Token, no login',
	authenticated: 'Nextcloud login',
}

/**
 * Read the app id and display name from appinfo/info.xml.
 *
 * @return {{id: string, name: string}}
 */
function appInfo() {
	const xml = fs.readFileSync(INFO_XML, 'utf8')
	const id = (xml.match(/<id>\s*([^<\s]+)\s*<\/id>/) || [])[1] || path.basename(ROOT)
	const name = (xml.match(/<name(?:\s+lang="en")?>\s*([^<]+?)\s*<\/name>/) || [])[1] || id
	return { id, name }
}

/**
 * Escape a value for a Markdown table cell.
 *
 * @param {string|number|undefined} value Cell value.
 * @return {string}
 */
function cell(value) {
	return String(value ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')
}

/**
 * A standard's name, linked to its specification when one is given.
 *
 * @param {object} standard Discovery standard entry.
 * @return {string}
 */
function named(standard) {
	return standard.specUrl ? `[${cell(standard.name)}](${standard.specUrl})` : cell(standard.name)
}

/**
 * The endpoint as a reader should see it: login-only endpoints are not
 * published by the server, so the docs say so rather than printing a path
 * a remote caller cannot use.
 *
 * @param {object} standard Discovery standard entry.
 * @return {string}
 */
function endpoint(standard) {
	if (!standard.endpoint) {
		return '—'
	}
	const access = standard.access || 'authenticated'
	return access === 'authenticated' ? `\`${standard.endpoint}\` (not published)` : `\`${standard.endpoint}\``
}

/**
 * Render the full docs page.
 *
 * @param {{id: string, name: string}} app App identity.
 * @param {object} discovery The manifest's `discovery` block (may be empty).
 * @return {string}
 */
function renderPage(app, discovery) {
	const standards = Array.isArray(discovery.standards) ? discovery.standards : []
	const provides = standards.filter((s) => s.role === 'provides')
	const consumes = standards.filter((s) => s.role === 'consumes')
	const links = discovery.links && typeof discovery.links === 'object' ? Object.entries(discovery.links) : []
	const ocm = Array.isArray(discovery.ocmResourceTypes) ? discovery.ocmResourceTypes : []
	const listed = discovery.public !== false && (standards.length > 0 || links.length > 0 || ocm.length > 0)

	const out = []
	out.push('---')
	out.push('title: Standards & federation')
	out.push('sidebar_position: 90')
	out.push(`description: Interoperability standards ${app.name} provides and uses, and how other servers discover them.`)
	out.push('---')
	out.push('')
	out.push('<!-- Generated by scripts/generate-standards-docs.cjs from the `discovery` block in src/manifest.json. Do not edit by hand: edit the manifest and run `npm run docs:standards`. -->')
	out.push('')
	out.push('# Standards & federation')
	out.push('')
	if (listed) {
		out.push(`${app.name} declares the standards below in its manifest. OpenRegister publishes them to other servers without login, under \`${app.id}.discovery\` in \`/ocs/v2.php/cloud/capabilities\`, so another instance can tell from a hostname alone whether it can connect. Tools such as [Nextcloud Peek](https://genhttp.dev/lambda/nextcloud-peek/) show it too.`)
	} else if (discovery.public === false) {
		out.push(`${app.name} declares the standards below but has opted out of publishing them (\`discovery.public: false\`). Other servers do not see this list.`)
	} else {
		out.push(`${app.name} declares no interoperability standards of its own. It is not listed in the public discovery capability.`)
	}
	out.push('')

	out.push('## Standards this app provides')
	out.push('')
	if (provides.length === 0) {
		out.push('None.')
	} else {
		out.push('| Standard | Version | Access | Endpoint |')
		out.push('|---|---|---|---|')
		for (const s of provides) {
			out.push(`| ${named(s)} | ${cell(s.version || '—')} | ${ACCESS[s.access || 'authenticated']} | ${endpoint(s)} |`)
		}
	}
	out.push('')

	out.push('## Standards this app uses')
	out.push('')
	if (consumes.length === 0) {
		out.push('None.')
	} else {
		out.push('These are standards the app acts as a client of. They tell another server what this app can connect *to*.')
		out.push('')
		out.push('| Standard | Version |')
		out.push('|---|---|')
		for (const s of consumes) {
			out.push(`| ${named(s)} | ${cell(s.version || '—')} |`)
		}
	}
	out.push('')

	if (links.length > 0) {
		out.push('## Public entry points')
		out.push('')
		out.push('| Name | Path |')
		out.push('|---|---|')
		for (const [name, target] of links) {
			out.push(`| ${cell(name)} | \`${cell(target)}\` |`)
		}
		out.push('')
	}

	out.push('## Federation (Open Cloud Mesh)')
	out.push('')
	if (ocm.length === 0) {
		out.push(`${app.name} registers no Open Cloud Mesh resource type of its own. Objects it stores in OpenRegister can still be shared with another instance through OpenRegister's \`openregister\` resource type.`)
	} else {
		out.push('These resource types are announced in `/.well-known/ocm` when Open Cloud Mesh federation is enabled on the instance.')
		out.push('')
		out.push('| Resource type | Share with | Protocols |')
		out.push('|---|---|---|')
		for (const t of ocm) {
			const protocols = Object.entries(t.protocols || {}).map(([k, v]) => `${k}: \`${v}\``).join(', ')
			out.push(`| \`${cell(t.name)}\` | ${cell((t.shareTypes || []).join(', '))} | ${protocols} |`)
		}
	}
	out.push('')

	out.push('## How another server finds this')
	out.push('')
	out.push('```bash')
	out.push("curl -s -H 'OCS-APIRequest: true' \\")
	out.push("  'https://cloud.example.org/ocs/v2.php/cloud/capabilities?format=json' \\")
	out.push(`  | jq '.ocs.data.capabilities["${app.id}"].discovery'`)
	out.push('```')
	out.push('')
	out.push('Paths are relative to the instance root. Prefix `/index.php` when the instance runs without pretty URLs (`core.mod-rewrite-working` is false). Endpoints that need a Nextcloud login are listed without their path.')
	out.push('')
	out.push('## Administrators')
	out.push('')
	out.push('- Stop publishing discovery for every app: `occ config:app:set openregister discovery_public --value=no`')
	out.push(`- Hide only this app: add \`${app.id}\` to \`occ config:app:set openregister discovery_hidden_apps --value=...\` (comma separated)`)
	out.push('')
	out.push(`Field reference and the shared list of standard ids: [Discovery and federation](${REFERENCE}).`)
	out.push('')
	return out.join('\n')
}

/**
 * Render the README section (between the markers, markers included).
 *
 * @param {{id: string, name: string}} app App identity.
 * @param {object} discovery The manifest's `discovery` block.
 * @return {string}
 */
function renderReadme(app, discovery) {
	const standards = Array.isArray(discovery.standards) ? discovery.standards : []
	const out = [START, '## Standards & federation', '']
	if (standards.length === 0) {
		out.push(`${app.name} declares no interoperability standards of its own.`)
	} else {
		out.push('| Standard | Role | Access |')
		out.push('|---|---|---|')
		for (const s of standards) {
			const role = s.role === 'provides' ? 'Provides' : 'Uses'
			out.push(`| ${named(s)}${s.version ? ` ${cell(s.version)}` : ''} | ${role} | ${s.role === 'provides' ? ACCESS[s.access || 'authenticated'] : '—'} |`)
		}
	}
	out.push('')
	out.push('Other servers can read this list without logging in, from the Nextcloud capabilities endpoint (published by OpenRegister). Details, federation and admin switches: [docs/standards-and-federation.md](docs/standards-and-federation.md).')
	out.push(END)
	return out.join('\n')
}

/**
 * Put the section into the README text, replacing an existing one.
 *
 * @param {string} readme Current README.
 * @param {string} section Rendered section.
 * @return {string}
 */
function placeInReadme(readme, section) {
	const start = readme.indexOf(START)
	const end = readme.indexOf(END)
	if (start !== -1 && end > start) {
		return readme.slice(0, start) + section + readme.slice(end + END.length)
	}
	for (const heading of ['## Standards & Compliance', '## Related Apps', '## License']) {
		const at = readme.search(new RegExp(`^${heading.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*$`, 'm'))
		if (at !== -1) {
			return readme.slice(0, at) + section + '\n\n' + readme.slice(at)
		}
	}
	return readme.replace(/\s*$/, '\n\n') + section + '\n'
}

/**
 * Read the `discovery` block, or an empty one for an app without a manifest
 * (an app that is not manifest-driven declares nothing and is not listed).
 *
 * @return {object}
 */
function readDiscovery() {
	if (!fs.existsSync(MANIFEST)) {
		return {}
	}
	const manifest = JSON.parse(fs.readFileSync(MANIFEST, 'utf8'))
	return manifest.discovery && typeof manifest.discovery === 'object' ? manifest.discovery : {}
}

/**
 * Write (or, with --check, verify) the docs page and the README section.
 *
 * @return {void}
 */
function main() {
	const check = process.argv.includes('--check')
	const discovery = readDiscovery()
	const app = appInfo()

	const page = renderPage(app, discovery)
	const readmeBefore = fs.existsSync(README) ? fs.readFileSync(README, 'utf8') : ''
	const readmeAfter = placeInReadme(readmeBefore, renderReadme(app, discovery))
	const pageBefore = fs.existsSync(PAGE) ? fs.readFileSync(PAGE, 'utf8') : ''

	const stale = []
	if (pageBefore !== page) {
		stale.push(path.relative(ROOT, PAGE))
	}
	if (readmeBefore !== readmeAfter) {
		stale.push(path.relative(ROOT, README))
	}

	if (check) {
		if (stale.length > 0) {
			console.error(`[standards-docs] out of date: ${stale.join(', ')}. Run: npm run docs:standards`)
			process.exit(1)
		}
		console.log('[standards-docs] up to date')
		return
	}

	fs.mkdirSync(path.dirname(PAGE), { recursive: true })
	fs.writeFileSync(PAGE, page)
	fs.writeFileSync(README, readmeAfter)
	console.log(stale.length > 0 ? `[standards-docs] wrote ${stale.join(', ')}` : '[standards-docs] already up to date')
}

main()
