        // Redact signing secrets on every list read.
        $redacted = array_map(
            fn($subscription) => $this->redactSubscription(subscription: $subscription->getObject()),
            $subscriptions
        );

        return new JSONResponse(['results' => $redacted]);

    }//end subscriptions()

