    /**
     * List all subscriptions.
     *
     * @return JSONResponse List of subscriptions.
     *
     * @NoAdminRequired
     * @NoCSRFRequired
     *
     * @spec openspec/changes/retrofit-2026-05-24-events-cloudevents/tasks.md#task-5
     */
    #[NoAdminRequired]
    #[NoCSRFRequired]
    public function subscriptions(): JSONResponse
    {
        $user = $this->userSession->getUser();
        if ($user === null) {
            return new JSONResponse(['error' => $this->l->t('Not authenticated')], Http::STATUS_UNAUTHORIZED);
        }

        $this->actionAuth->requireAction(user: $user, action: 'event.subscriptions');

        $filters = $this->request->getParams();

        // Remove internal fields.
        foreach ($filters as $key => $value) {
            if (str_starts_with($key, '_') === true) {
                unset($filters[$key]);
            }
        }

        $orFilters     = array_merge(['register' => 'openconnector', 'schema' => 'event_subscription'], $filters);
